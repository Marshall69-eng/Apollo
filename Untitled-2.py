# ---------------------------------------------------------------
# Database helpers
# ---------------------------------------------------------------
def get_db() -> sqlite3.Connection:
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    return conn


def init_db() -> None:
    conn = get_db()
    cur = conn.cursor()
    cur.execute(
        """
        CREATE TABLE IF NOT EXISTS sites (
            id TEXT PRIMARY KEY,
            name TEXT NOT NULL,
            flow REAL, debris REAL, flood REAL, solar REAL
        )
        """
    )
    cur.execute(
        """
        CREATE TABLE IF NOT EXISTS readings (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            site_id TEXT NOT NULL,
            ts TEXT NOT NULL,
            flow REAL, debris REAL, flood REAL, solar REAL, score INTEGER
        )
        """
    )
    cur.execute(
        """
        CREATE TABLE IF NOT EXISTS units (
            id TEXT PRIMARY KEY,
            site_id TEXT NOT NULL,
            deployed_at TEXT NOT NULL,
            plastic_load REAL,
            bales INTEGER,
            active INTEGER DEFAULT 1
        )
        """
    )
    cur.execute("SELECT COUNT(*) AS c FROM sites")
    if cur.fetchone()["c"] == 0:
        cur.executemany(
            "INSERT INTO sites (id, name, flow, debris, flood, solar) VALUES (?,?,?,?,?,?)",
            SEED_SITES,
        )
    conn.commit()
    conn.close()


# ---------------------------------------------------------------
# Response models
# ---------------------------------------------------------------
class Site(BaseModel):
    id: str
    name: str
    flow: float
    debris: float
    flood: float
    solar: float
    score: int


class Unit(BaseModel):
    id: str
    site_id: str
    site_name: str
    deployed_at: str
    flow: float
    flood_alert: str
    plastic_load: float
    bales: int


# ---------------------------------------------------------------
# Background sensor simulation — the only place touching fake
# data. Swap this out for real buoy ingestion when hardware is
# ready; every route below just reads whatever is in the DB.
# ---------------------------------------------------------------
async def simulate_tick() -> None:
    while True:
        await asyncio.sleep(3)
        conn = get_db()
        cur = conn.cursor()

        rows = cur.execute("SELECT * FROM sites").fetchall()
        for r in rows:
            flow = clamp(r["flow"] + random.uniform(-0.09, 0.09), 0.2, 3.6)
            debris = clamp(r["debris"] + random.uniform(-2, 2), 5, 98)
            flood = clamp(r["flood"] + random.uniform(-1, 1), 10, 98)
            solar = clamp(r["solar"] + random.uniform(-1, 1), 20, 99)
            score = composite_score(flow, debris, flood, solar)

            cur.execute(
                "UPDATE sites SET flow=?, debris=?, flood=?, solar=? WHERE id=?",
                (flow, debris, flood, solar, r["id"]),
            )
            cur.execute(
                "INSERT INTO readings (site_id, ts, flow, debris, flood, solar, score) "
                "VALUES (?,?,?,?,?,?,?)",
                (r["id"], datetime.now(timezone.utc).isoformat(), flow, debris, flood, solar, score),
            )

        units = cur.execute("SELECT * FROM units WHERE active=1").fetchall()
        for u in units:
            plastic_load = clamp(u["plastic_load"] + random.uniform(-3, 3), 10, 98)
            bales = u["bales"] + (1 if random.random() < 0.15 else 0)
            cur.execute(
                "UPDATE units SET plastic_load=?, bales=? WHERE id=?",
                (plastic_load, bales, u["id"]),
            )

        conn.commit()
        conn.close()


@asynccontextmanager
async def lifespan(app: FastAPI):
    init_db()
    task = asyncio.create_task(simulate_tick())
    yield
    task.cancel()


app = FastAPI(title="NetZero Wave API", lifespan=lifespan)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],  # fine for a local prototype; scope this down before deploying
    allow_methods=["*"],
    allow_headers=["*"],
)


def _unit_response(u: sqlite3.Row, site_name: str, flow: float, flood: float) -> Unit:
    return Unit(
        id=u["id"],
        site_id=u["site_id"],
        site_name=site_name,
        deployed_at=u["deployed_at"],
        flow=flow,
        flood_alert=alert_level(flow, flood),
        plastic_load=u["plastic_load"],
        bales=u["bales"],
    )


