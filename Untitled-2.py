"""
Storm Baler backend prototype (FastAPI)
========================================

Serves the site-selection scoring model and live unit-monitoring
data over a REST API, backed by a local SQLite file. A background
task simulates buoy sensor drift every 3 seconds and writes each
reading to the database, so the API looks and behaves like a real
live feed even before any hardware is wired up.

To go from prototype to production: replace `simulate_tick()`
with your real buoy ingestion (MQTT subscriber, LoRaWAN webhook,
etc.) that calls the same `UPDATE sites ...` / `INSERT INTO
readings ...` statements. Nothing else in the API needs to change.

Run:
    pip install -r requirements.txt
    uvicorn main:app --reload

Interactive API docs (auto-generated by FastAPI):
    http://127.0.0.1:8000/docs
"""

import asyncio
import random
import sqlite3
from contextlib import asynccontextmanager
from datetime import datetime, timezone
from typing import List

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel

DB_PATH = "storm_baler.db"

# ---------------------------------------------------------------
# Scoring model — mirrors the frontend prototype's weights/curve.
# Tune these to match your paper's actual methodology; they are
# reasonable placeholders, not derived from your source material.
# ---------------------------------------------------------------
WEIGHTS = {"flow": 0.30, "debris": 0.30, "flood": 0.25, "solar": 0.15}


def flow_score(v: float) -> float:
    """Rewards flow velocity inside the 0.5-3.0 m/s ideal band."""
    if v < 0.5:
        return (v / 0.5) * 60
    if v <= 3.0:
        return 60 + ((v - 0.5) / 2.5) * 40
    return max(40, min(100, 100 - (v - 3.0) * 15))


def composite_score(flow: float, debris: float, flood: float, solar: float) -> int:
    fs = flow_score(flow)
    total = (
        fs * WEIGHTS["flow"]
        + debris * WEIGHTS["debris"]
        + flood * WEIGHTS["flood"]
        + solar * WEIGHTS["solar"]
    )
    return round(total)


def clamp(v: float, lo: float, hi: float) -> float:
    return max(lo, min(hi, v))


def alert_level(flow: float, flood: float) -> str:
    risk = flow * 20 + flood * 0.5
    if risk > 95:
        return "High"
    if risk > 60:
        return "Moderate"
    return "Low"


